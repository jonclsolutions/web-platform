#!/usr/bin/env bash
# =============================================================================
# @file build.sh
# @path deploy/build.sh
# @project RPSW Web
# @author RPSW
# @created 2026
# @description Production build of the whole platform into a single deployable
# package. Replaces the former root-level `build-and-deploy.sh`.
#
# Output (in <root>/build/, git-ignored, wiped on every run):
#   build/
#   ├── www/                 → upload to the hosting webroot
#   │   ├── (Angular browser build: index.html, chunks, assets)
#   │   ├── (deploy/server/*: .htaccess, .user.ini, configure-server.sh)
#   │   └── laravel/         → Laravel API, production dependencies only
#   ├── www.zip              → the same www/ as one archive
#   ├── www.zip.sha256       → checksum to verify the upload
#   └── README.md, server_setup.* (preview only, NOT part of www)
#
# @note WHAT IS DELIBERATELY NOT SHIPPED (security / GDPR):
#   - api/.env and any .env.* except .env.example (local secrets)
#   - storage/logs, framework cache/sessions/views (may contain personal data)
#   - storage/app/private (user uploads: CVs, attachments, tickets = personal
#     data; production keeps its own and a deploy must never overwrite them)
#   - storage/app/public by default (admin uploads such as product images –
#     shipping local test files would overwrite production ones); include it
#     only for a first install with --with-public-storage
#   - dev dependencies (composer --no-dev), tests, IDE helpers, node_modules,
#     VCS metadata, local helper scripts, private keys
#   A final scan aborts the build if anything secret-looking ends up in www/.
#
# @note bootstrap/cache/*.php is regenerated by `composer install --no-dev`
# (package:discover). Copying the local one would reference dev-only service
# providers (e.g. ide-helper) and crash production with "Class not found".
#
# @security The package layout keeps Laravel inside www/laravel. The server
# config (deploy/server/.htaccess) MUST deny direct HTTP access to everything
# under /laravel except the routed entry point, otherwise laravel/.env,
# storage and vendor would be publicly reachable.
#
# @note TESTS FIRST (2026-10-24): every build runs all unit tests (tests/unit_tests/run_all.sh
#   - erp + api) before anything is deleted or built. Only when all of them pass does the real
#   build start; a failure stops the script (exit 1) and the previous build/ stays untouched.
#   --skip-tests skips the gate (e.g. an urgent rebuild of an already tested commit).
#
# @refactor-note (2026-10-31) The root folder database/ (SQL dump + manual SQL scripts) was
#   removed - the build no longer copies database/*.sql to build/database/. The schema reaches
#   the server inside laravel/ (api/database: baseline SQL + migrations, run by configure-server.sh).
#
# @usage
#   deploy/build.sh                         run all tests, then the full build (Angular + Laravel + zip)
#   deploy/build.sh --skip-tests            build without running the tests first
#   deploy/build.sh --with-public-storage   also ship storage/app/public (first install)
#   deploy/build.sh --skip-angular          reuse existing erp/dist (faster rebuild)
#   deploy/build.sh --no-zip                skip the archive step
# =============================================================================

set -Eeuo pipefail

# -----------------------------------------------------------------------------
# Paths – derived from the script location, so it works from any directory.
# -----------------------------------------------------------------------------
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT_DIR="$(cd "$SCRIPT_DIR/.." && pwd)"

API_DIR="$ROOT_DIR/api"
ERP_DIR="$ROOT_DIR/erp"
SERVER_CONF_DIR="$SCRIPT_DIR/server"

BUILD_DIR="$ROOT_DIR/build"
WWW_DIR="$BUILD_DIR/www"
LARAVEL_TARGET="$WWW_DIR/laravel"
ZIP_NAME="www.zip"

# Angular output path follows the project name in erp/angular.json.
ANGULAR_PROJECT="${ANGULAR_PROJECT:-rp_website}"
DIST_DIR="$ERP_DIR/dist/$ANGULAR_PROJECT/browser"

WITH_PUBLIC_STORAGE=0
SKIP_ANGULAR=0
SKIP_TESTS=0
TESTS_RUNNER="$ROOT_DIR/tests/unit_tests/run_all.sh"
MAKE_ZIP=1

# -----------------------------------------------------------------------------
# Output helpers
# -----------------------------------------------------------------------------
STEP=0
TOTAL_STEPS=9
step() { STEP=$((STEP + 1)); printf '\n\e[34m[%d/%d]\e[0m %s\n' "$STEP" "$TOTAL_STEPS" "$*"; }
info() { printf '   - %s\n' "$*"; }
warn() { printf '\e[33m   ! %s\e[0m\n' "$*" >&2; }
die()  { printf '\e[31mERROR: %s\e[0m\n' "$*" >&2; exit 1; }

# Any unexpected failure reports the line, instead of a silently half-built package.
# The ERR trap is inherited by subshells (set -E); report only from the main
# shell so one failure is not printed twice.
trap '[[ $BASH_SUBSHELL -eq 0 ]] && die "build failed at line $LINENO (command: $BASH_COMMAND)"; exit 1' ERR

# -----------------------------------------------------------------------------
# Arguments
# -----------------------------------------------------------------------------
for arg in "$@"; do
    case "$arg" in
        --with-public-storage) WITH_PUBLIC_STORAGE=1 ;;
        --skip-angular)        SKIP_ANGULAR=1 ;;
        --skip-tests)          SKIP_TESTS=1 ;;
        --no-zip)              MAKE_ZIP=0 ;;
        -h|--help) sed -n '/^# @usage/,/^# =====/p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//' | sed '$d'; exit 0 ;;
        *) die "unknown option: $arg (see --help)" ;;
    esac
done

# -----------------------------------------------------------------------------
# @description Fails fast on missing tools or directories, before anything is
# deleted, so a broken environment never leaves you without the previous build.
# -----------------------------------------------------------------------------
preflight() {
    step "Checking prerequisites"
    local cmd
    for cmd in rsync composer php; do
        command -v "$cmd" >/dev/null || die "'$cmd' is not installed"
    done
    [[ "$MAKE_ZIP" == "1" ]] && { command -v zip >/dev/null || die "'zip' is not installed (or use --no-zip)"; }
    [[ "$SKIP_ANGULAR" == "1" ]] || command -v npx >/dev/null || die "'npx' (Node.js) is not installed"

    [[ -f "$API_DIR/composer.json" ]] || die "Laravel not found in $API_DIR"
    [[ -f "$ERP_DIR/angular.json" ]]  || die "Angular not found in $ERP_DIR"
    [[ -d "$SERVER_CONF_DIR" ]]       || die "server config not found in $SERVER_CONF_DIR"

    # Fail before the (slow) Angular build if the PHP used by Composer cannot
    # satisfy composer.lock (PHP version or missing extensions). Composer prints
    # exactly which requirement fails.
    # The lock file pins the exact tested dependency versions – never build without it.
    [[ -f "$API_DIR/composer.lock" ]] || die "api/composer.lock is missing – run 'composer install' in api/ and commit the lock file"
    info "PHP used by Composer: $(php -r 'echo PHP_VERSION;') ($(command -v php))"
    if ! (cd "$API_DIR" && composer check-platform-reqs --lock --no-dev --no-interaction >/dev/null 2>&1); then
        (cd "$API_DIR" && composer check-platform-reqs --lock --no-dev --no-interaction) | grep -vE '\bsuccess\b' >&2 || true
        die "local PHP does not satisfy api/composer.lock (see 'failed'/'missing' lines above)"
    fi

    if git -C "$ROOT_DIR" rev-parse --is-inside-work-tree >/dev/null 2>&1; then
        if [[ -n "$(git -C "$ROOT_DIR" status --porcelain -- api erp deploy)" ]]; then
            warn "uncommitted changes in api/, erp/ or deploy/ – the package will not match any commit"
        fi
        info "commit: $(git -C "$ROOT_DIR" rev-parse --short HEAD)"
    fi
    info "OK"
}

# -----------------------------------------------------------------------------
# @description Recreates the build directory. Guarded so a misconfigured path
# can never make `rm -rf` hit anything outside the repository.
# -----------------------------------------------------------------------------
prepare_build_dir() {
    step "Preparing $BUILD_DIR"
    [[ "$BUILD_DIR" == "$ROOT_DIR/build" ]] || die "refusing to delete unexpected path: $BUILD_DIR"
    rm -rf "$BUILD_DIR"
    mkdir -p "$WWW_DIR" "$LARAVEL_TARGET"
    info "clean build directory created"
}

# -----------------------------------------------------------------------------
# @description Production Angular build, copied to the webroot of the package.
# -----------------------------------------------------------------------------
build_angular() {
    step "Building Angular (production)"
    if [[ "$SKIP_ANGULAR" == "1" ]]; then
        info "skipped (--skip-angular), reusing existing dist"
    else
        (cd "$ERP_DIR" && npx ng build --configuration production)
    fi
    [[ -f "$DIST_DIR/index.html" ]] || die "Angular output not found in $DIST_DIR (check ANGULAR_PROJECT)"
    rsync -a "$DIST_DIR/" "$WWW_DIR/"
    info "Angular copied to build/www/"
}

# -----------------------------------------------------------------------------
# @description Copies Laravel without secrets, personal data or dev tooling,
# then installs production-only dependencies inside the copy (the local
# api/vendor with dev packages is never touched or shipped).
# -----------------------------------------------------------------------------
build_laravel() {
    step "Preparing Laravel (no secrets, no dev dependencies)"

    local excludes=(
        # secrets & local environment
        # (rsync uses the first matching rule, so the include must come first)
        --include='/.env.example' --exclude='/.env' --exclude='/.env.*'
        --exclude='*.pem' --exclude='*.key' --exclude='id_rsa*' --exclude='id_ed25519*'
        # dependencies – reinstalled below with --no-dev
        --exclude='/vendor/' --exclude='/node_modules/'
        # dev tooling & local helpers
        --exclude='/tests/' --exclude='/phpunit.xml' --exclude='/_ide_helper*.php'
        --exclude='/.phpstorm.meta.php' --exclude='/scripts/' --exclude='/.git/'
        --exclude='/.gitattributes' --exclude='/.editorconfig' --exclude='/.idea/' --exclude='/.vscode/'
        # local runtime state (regenerated on the server)
        --exclude='/bootstrap/cache/*.php'
        --exclude='/storage/logs/*' --exclude='/storage/framework/cache/data/*'
        --exclude='/storage/framework/sessions/*' --exclude='/storage/framework/views/*'
        --exclude='/storage/framework/testing/*'
        # personal data – production keeps its own uploads
        --exclude='/storage/app/private/*'
        # local symlink to the developer's disk; recreate with `php artisan storage:link`
        --exclude='/public/storage'
    )
    if [[ "$WITH_PUBLIC_STORAGE" == "0" ]]; then
        excludes+=(--exclude='/storage/app/public/*')
    fi

    rsync -a "${excludes[@]}" "$API_DIR/" "$LARAVEL_TARGET/"

    # Keep the empty storage skeleton Laravel expects on the server.
    mkdir -p "$LARAVEL_TARGET"/storage/{logs,app/private,app/public} \
             "$LARAVEL_TARGET"/storage/framework/{cache/data,sessions,views} \
             "$LARAVEL_TARGET"/bootstrap/cache

    if [[ "$WITH_PUBLIC_STORAGE" == "1" ]]; then
        warn "storage/app/public included – deploying it OVERWRITES production uploads"
    else
        info "storage/app/public not shipped (use --with-public-storage for a first install)"
    fi

    info "installing production dependencies (composer --no-dev)"
    (cd "$LARAVEL_TARGET" && composer install --no-dev --optimize-autoloader \
        --classmap-authoritative --no-interaction --no-progress)
    info "Laravel copied to build/www/laravel"
}

# -----------------------------------------------------------------------------
# @description Server configuration (.htaccess, .user.ini, setup script).
# -----------------------------------------------------------------------------
copy_server_conf() {
    step "Copying server configuration"
    rsync -a --exclude='*.sql' "$SERVER_CONF_DIR/" "$WWW_DIR/"
    [[ -f "$WWW_DIR/.htaccess" ]] || warn "no .htaccess in deploy/server – /laravel would NOT be protected"
    info "deploy/server copied to build/www/"
}

# -----------------------------------------------------------------------------
# @description Documentation goes to the build ROOT only – never into www/, so it cannot be
# downloaded from the website.
# -----------------------------------------------------------------------------
copy_extras() {
    step "Copying docs (outside www)"
    local f
    for f in README.md README.txt server_setup.md server_setup.txt; do
        [[ -f "$ROOT_DIR/$f" ]] && { cp "$ROOT_DIR/$f" "$BUILD_DIR/"; info "$f copied to build root"; }
    done
    return 0
}

# -----------------------------------------------------------------------------
# @description Last line of defence: aborts if anything secret-looking or any
# SQL dump made it into the public package, whatever the cause.
# -----------------------------------------------------------------------------
verify_package() {
    step "Verifying package contents"
    local leaks
    leaks="$(find "$WWW_DIR" \( -name '.env' -o -name '.env.*' ! -name '.env.example' \
        -o -name '*.sql' -o -name '*.key' -o -name '*.pem' -o -name 'id_rsa*' -o -name 'id_ed25519*' \
        -o -name '*.log' \) -print)"
    [[ -z "$leaks" ]] || die "sensitive files found in build/www – aborting:"$'\n'"$leaks"

    [[ -d "$LARAVEL_TARGET/vendor" ]] || die "vendor/ missing in the Laravel package"
    if [[ -d "$LARAVEL_TARGET/storage/app/private" ]] \
        && [[ -n "$(find "$LARAVEL_TARGET/storage/app/private" -type f -print -quit)" ]]; then
        die "personal data found in storage/app/private – aborting"
    fi
    info "no secrets, dumps, logs or private uploads in www/"
}

# -----------------------------------------------------------------------------
# @description Test gate: runs ALL unit tests (erp + api, tests/unit_tests/run_all.sh) before
# the build. Runs right after preflight - before build/ is wiped - so a failure leaves the
# previous package in place. The ERR trap is suspended while the runner works (its non-zero
# exit code is the expected "tests failed" answer, not a script error).
# Exit codes of the runner: 0 all passed, 1 a test failed, 2 a part could not run (setup).
# -----------------------------------------------------------------------------
run_tests() {
    step "Running all unit tests (erp + api)"
    if [[ "$SKIP_TESTS" == "1" ]]; then
        warn "skipped (--skip-tests) – the package is built WITHOUT running the tests"
        return 0
    fi
    [[ -f "$TESTS_RUNNER" ]] || die "test runner not found: $TESTS_RUNNER (or use --skip-tests)"

    local rc=0
    trap - ERR
    bash "$TESTS_RUNNER" || rc=$?
    trap '[[ $BASH_SUBSHELL -eq 0 ]] && die "build failed at line $LINENO (command: $BASH_COMMAND)"; exit 1' ERR

    echo
    case "$rc" in
        0) printf '\e[32m   ✓ ALL TESTS PASSED – starting the production build\e[0m\n' ;;
        1) die "tests FAILED – the build was NOT started (details: tests/unit_tests/report/report.html; --skip-tests builds anyway)" ;;
        *) die "the tests could not run (exit code $rc, setup problem – see above) – the build was NOT started (--skip-tests builds anyway)" ;;
    esac
}

# -----------------------------------------------------------------------------
# @description Archive + SHA-256 checksum so the upload can be verified.
# -----------------------------------------------------------------------------
make_archive() {
    step "Creating $ZIP_NAME"
    if [[ "$MAKE_ZIP" == "0" ]]; then
        info "skipped (--no-zip)"
        return 0
    fi
    (cd "$BUILD_DIR" && zip -qr "$ZIP_NAME" www && sha256sum "$ZIP_NAME" > "$ZIP_NAME.sha256")
    info "build/$ZIP_NAME ($(du -h "$BUILD_DIR/$ZIP_NAME" | cut -f1))"
    info "checksum: $(cut -d' ' -f1 "$BUILD_DIR/$ZIP_NAME.sha256")"
}

# -----------------------------------------------------------------------------
# Main
# -----------------------------------------------------------------------------
echo "------------------------------------------"
echo "START: Production build"
echo "------------------------------------------"
preflight
run_tests
prepare_build_dir
build_angular
build_laravel
copy_server_conf
copy_extras
verify_package
make_archive
echo
echo "------------------------------------------"
echo "COMPLETE: package ready in build/"
echo "------------------------------------------"
